"""Build the two Cnblogs fields and their hosted assets (Python standard library)."""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / 'src'
CSS = ('critical', 'tokens', 'layout', 'prose', 'pages')


def compact(css):
    # Touch layout whitespace only. Preserve quoted strings, escaped characters,
    # descendant combinators, and spaces around calc's arithmetic operators.
    tokens = re.findall(
        r""""(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*'|/\*.*?\*/|\\.|\s+|[^\s]""", css, re.DOTALL
    )
    result = []
    pending = False
    for token in tokens:
        if token.isspace() or token.startswith('/*'):
            pending = True
            continue
        # None of these four delimiters needs adjacent whitespace. In particular,
        # ':' is NOT in this set: '#body :is(...)' is a descendant selector.
        if pending and result and result[-1] not in '{},;' and token not in '{},;':
            result.append(' ')
        result.append(token)
        pending = False
    return ''.join(result) + '\n'


def files(repo, ref, version):
    critical, *layers = [(SRC / f'css/{name}.css').read_text('utf-8') for name in CSS]
    boot = (SRC / 'js/core/boot.js').read_text('utf-8')
    headers = [re.match(r'/\* ctp-docs v(\d+\.\d+\.\d+)\b', s) for s in (critical, boot)]
    if not all(headers) or headers[0][1] != headers[1][1] or version not in (None, headers[0][1]):
        raise ValueError('version mismatch: agree on X.Y.Z in critical.css, boot.js and --version')
    ref = ref or 'v' + headers[0][1]
    segment = r'[A-Za-z0-9_][A-Za-z0-9_.-]*'
    if not re.fullmatch(segment + '/' + segment, repo) or not re.fullmatch(segment, ref):
        raise ValueError(
            '--repo must be OWNER/REPO; --ref must be a single tag, branch name or commit'
        )
    head = (SRC / 'templates/head-loader.html').read_text('utf-8')
    for token, host in [('PRIMARY', 'cdn'), ('MIRROR', 'fastly')]:
        head = head.replace(
            '{{' + token + '}}', f'https://{host}.jsdelivr.net/gh/{repo}@{ref}/dist/'
        )
    css = '\n'.join([critical, *layers])
    small = compact(css)
    js = '\n'.join(
        p.read_text('utf-8')
        for part in ('core', 'data', 'ui')
        for p in sorted((SRC / 'js' / part).glob('*.js'))
    )
    fallback = (
        (SRC / 'templates/css-fallback.js')
        .read_text('utf-8')
        .replace('{{CSS}}', json.dumps(small, ensure_ascii=False))
    )
    js = fallback + '\n' + js
    return {
        'ctp-docs.css': css,
        'ctp-docs.min.css': small,
        'ctp-docs.js': js,
        'paste/样式.min.css': compact(critical),
        'paste/页首.html': head,
        'fallback/样式-内联备份.css': small.replace('--ctp-field:2', '--ctp-field:1', 1),
    }


def main():
    cli = argparse.ArgumentParser(description=__doc__)
    cli.add_argument('--out', type=Path, default=ROOT / 'dist')
    cli.add_argument('--check', action='store_true', help='compare generated bytes without writing')
    cli.add_argument(
        '--repo',
        default='sunstrikes/cnblogs-theme',
        help='public GitHub OWNER/REPO containing dist at its root',
    )
    cli.add_argument('--ref', help='published Git ref (default: v followed by the source version)')
    cli.add_argument('--version', help='require both source version headers to match X.Y.Z')
    args = cli.parse_args()
    try:
        outputs = files(args.repo, args.ref, args.version)
    except ValueError as exc:
        cli.error(str(exc))
    stale = []
    for filename, content in outputs.items():
        path = args.out / filename
        expected = content.encode('utf-8')
        if args.check:
            if not path.is_file() or path.read_bytes() != expected:
                stale.append(filename)
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(expected)
    if stale:
        print(
            'Missing or stale; rebuild with the same arguments: ' + ', '.join(stale),
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == '__main__':
    sys.exit(main())
